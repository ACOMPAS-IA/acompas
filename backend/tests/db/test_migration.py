"""Migración inicial: upgrade, check, downgrade y vuelta (AC-01 y AC-05)."""

from __future__ import annotations

from pathlib import Path

import pytest
import sqlalchemy as sa
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy.engine import Engine

BACKEND = Path(__file__).resolve().parents[2]
ALEMBIC_INI = BACKEND / "alembic.ini"

TABLAS_DEL_MODELO = 18


def config() -> Config:
    return Config(str(ALEMBIC_INI))


def tablas(url: str) -> set[str]:
    engine = sa.create_engine(url)
    try:
        return set(sa.inspect(engine).get_table_names())
    finally:
        engine.dispose()


def extension_vector(url: str) -> bool:
    engine = sa.create_engine(url)
    try:
        with engine.connect() as connection:
            return bool(
                connection.execute(
                    sa.text(
                        "SELECT count(*) FROM pg_extension "
                        "WHERE extname = 'vector'"
                    )
                ).scalar_one()
            )
    finally:
        engine.dispose()


def test_upgrade_crea_las_tablas_y_check_no_difiere(migrated: str) -> None:
    """`upgrade head` sobre una base vacía y `alembic check` sin diferencias."""
    assert len(tablas(migrated) - {"alembic_version"}) == TABLAS_DEL_MODELO
    assert extension_vector(migrated)
    command.check(config())


def test_downgrade_deja_la_base_sin_tablas(migrated: str) -> None:
    """`downgrade base` no deja tablas del modelo y conserva la extensión."""
    command.downgrade(config(), "base")
    assert tablas(migrated) == {"alembic_version"}
    assert extension_vector(migrated)


def test_downgrade_y_vuelta_a_head(migrated: str) -> None:
    """Bajar y volver a subir reconstruye el mismo esquema."""
    command.downgrade(config(), "base")
    command.upgrade(config(), "head")
    assert len(tablas(migrated) - {"alembic_version"}) == TABLAS_DEL_MODELO
    command.check(config())


def test_check_detecta_un_esquema_desviado(engine: Engine) -> None:
    """`alembic check` no es un adorno: detecta una tabla que falta.

    Se borra una tabla del modelo y se comprueba que `check` se queja. Sin esta
    prueba, un `check` que siempre pasara parecería correcto.
    """
    with engine.begin() as connection:
        connection.execute(sa.text("DROP TABLE entrada_glosario"))
    with pytest.raises(AutogenerateDiffsDetected):
        command.check(config())
